TEST(TableFreshness, MeasuredJsonNamesEveryShippedFunction) {
    std::string error;
    const std::vector<ParsedFunction> functions = load(&error);
    ASSERT_TRUE(error.empty()) << error;
    const char* expected[] = {"exp", "exp2", "log", "log1p", "log2", "rsqrt", "tanh"};
    for (const char* name : expected) {
        const ParsedFunction* function = find(functions, name);
        ASSERT_NE(function, nullptr) << "data/error-bounds.json has no " << name << " entry";
        EXPECT_GT(function->buckets.size(), 0u) << name << " has no buckets";
    }
}

TEST(TableFreshness, ExpBoundsMatchTheMeasuredJson) {
    std::string error;
    const std::vector<ParsedFunction> functions = load(&error);
    ASSERT_TRUE(error.empty()) << error;
    const ParsedFunction* function = find(functions, "exp");
    ASSERT_NE(function, nullptr) << "data/error-bounds.json has no exp entry";

    SCOPED_TRACE("exp");
    expect_matches(*function, ulpgrad::exp_error_bounds, ulpgrad::exp_error_bounds_count,
                   ulpgrad::exp_max_ulp);
}

