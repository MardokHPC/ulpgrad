#!/usr/bin/env python3
"""Generate the declared error table from the measured one.

Input, single source of truth:

    data/error-bounds.json      written by tools/measure_bounds.cpp from the
                                committed golden reference in data/reference/

Outputs, two views of the same numbers:

    docs/error-tables.md        the table a human reads
    include/ulpgrad/tables.h    the table the code reads

Both are derived, neither is hand-edited: if the markdown and the header
diverged, the test that compares the header against the JSON would be blind to
the half nobody checks. The freshness test (tests/test_table_freshness.cpp)
re-reads the JSON and compares it with the header, so editing either by hand
fails the build.

Run from the repository root::

    python tools/gen_table.py
"""

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)

HEADER_PATH = os.path.join(REPO, 'include', 'ulpgrad', 'tables.h')
MARKDOWN_PATH = os.path.join(REPO, 'docs', 'error-tables.md')

PROVENANCE = (
    'Generated by tools/gen_table.py from data/error-bounds.json -- do not edit by hand.'
)

# One suite per public header. Kept here rather than derived from the function
# names because the mapping is a documentation fact, not a property of the
# measurement: `ext` and `exp2` share `test_exp.cpp`, and that file is not named
# after the measurement.
SUITES = [
    'tests/test_exp.cpp',
    'tests/test_log.cpp',
    'tests/test_rsqrt.cpp',
    'tests/test_tanh.cpp',
    'tests/test_special_cases.cpp',
    'tests/test_table_freshness.cpp',
]


# --------------------------------------------------------------------------- #
# tables.h
# --------------------------------------------------------------------------- #


def emit_header(data, path):
    functions = data['functions']

    lines = []
    lines.append('#pragma once')
    lines.append('')
    lines.append('// ' + PROVENANCE)
    lines.append('')
    lines.append('namespace ulpgrad {')
    lines.append('')
    lines.append('// One row of the declared error table: an |x| bucket and its bound.')
    lines.append('struct ErrorBound {')
    lines.append('    const char* range;')
    lines.append('    int max_ulp;')
    lines.append('    long long points;')
    lines.append('};')
    lines.append('')
    for function in functions:
        name = function['name']
        lines.append('// Declared bound for %s, %s points, %.2f%% exactly rounded.'
                     % (name, format(function['measured_points'], ','),
                        function['exactly_rounded_pct']))
        lines.append('constexpr int %s_max_ulp = %d;' % (name, function['max_ulp']))
        lines.append('')
        lines.append('constexpr ErrorBound %s_error_bounds[] = {' % name)
        for bucket in function['buckets']:
            lines.append('    {"%s", %d, %dLL},  // %.2f%% exactly rounded'
                         % (bucket['range'], bucket['max_ulp'], bucket['points'],
                            bucket['exactly_rounded_pct']))
        lines.append('};')
        lines.append('')
        lines.append('constexpr int %s_error_bounds_count = %d;' %
                     (name, len(function['buckets'])))
        lines.append('')
    lines.append('}  // namespace ulpgrad')
    lines.append('')
    with open(path, 'w', encoding='ascii', newline='\n') as handle:
        handle.write('\n'.join(lines))


# --------------------------------------------------------------------------- #
# error-tables.md
# --------------------------------------------------------------------------- #


def emit_markdown(data, path):
    functions = data['functions']
    machine = data['machine']
    lines = []
    lines.append('# Error tables')
    lines.append('')
    lines.append('<!-- %s -->' % PROVENANCE)
    lines.append('')
    lines.append('Every bound in this file and in `include/ulpgrad/tables.h` comes from one')
    lines.append('measurement, and the same measurement produces both: change a coefficient and')
    lines.append('the numbers move together, or they do not move at all.')
    lines.append('')
    lines.append('| step | file |')
    lines.append('|---|---|')
    lines.append('| golden reference | %s |'
                 % ', '.join('`data/reference/%s.csv`' % f['name'] for f in functions))
    lines.append('| reference arithmetic | `experiments/m3_fit/gen_golden.py`, mpmath at 40 '
                 'digits, direct RNE |')
    lines.append('| the run being measured | `tools/measure_bounds.cpp`, this build |')
    lines.append('| measured numbers | `data/error-bounds.json` |')
    lines.append('| declared numbers | `include/ulpgrad/tables.h`, this file |')
    lines.append('| tests that keep them honest | %s |'
                 % ', '.join('`%s`' % name for name in SUITES))
    lines.append('')
    lines.append('## Measurement environment')
    lines.append('')
    lines.append('| item | value |')
    lines.append('|---|---|')
    lines.append('| date | %s |' % data['date'])
    lines.append('| OS / arch | %s / %s |' % (machine['os'], machine['arch']))
    lines.append('| CPU | %s |' % machine['cpu'])
    lines.append('| compiler | %s |' % machine['compiler'])
    lines.append('')
    lines.append('The ULP distance is computed on the monotone integer image of the bit')
    lines.append('pattern (`ulp_distance` in `include/ulpgrad/detail/bits.h`), so `+0` and')
    lines.append('`-0` are 0 ULP apart and adjacent floats are 1 apart across zero, across the')
    lines.append('subnormal boundary and across the infinities. A NaN pattern has no position')
    lines.append('on that order, so every comparison that involves one is done bit for bit')
    lines.append('instead: the NaN an argument carries, and the NaN a domain contract returns')
    lines.append('for a real argument, such as `log(-1)`.')
    lines.append('')
    for function in functions:
        lines.append('## `%s`' % function['name'])
        lines.append('')
        lines.append('| metric | value |')
        lines.append('|---|---|')
        lines.append('| points in the golden file | %s |' % format(function['points'], ','))
        lines.append('| points carrying a ULP distance | %s |' %
                     format(function['measured_points'], ','))
        lines.append('| NaN inputs, checked bit for bit | %s (%d mismatches) |' %
                     (format(function['nan_inputs'], ','), function['nan_mismatches']))
        lines.append('| NaN results for a real argument | %s |' %
                     format(function.get('nan_outputs', 0), ','))
        lines.append('| **max ULP** | **%d** |' % function['max_ulp'])
        lines.append('| exactly rounded | %.2f %% |' % function['exactly_rounded_pct'])
        lines.append('| worst input | `%s` |' % function['worst_input'])
        lines.append('| reference | %s |' % function['reference'])
        lines.append('| sample seed | `%s` |' % function['seed'])
        lines.append('')
        lines.append('| `\\|x\\|` | points | max ULP | exactly rounded |')
        lines.append('|---|---:|---:|---:|')
        for bucket in function['buckets']:
            lines.append('| %s | %s | %d | %.2f %% |'
                         % (bucket['range'], format(bucket['points'], ','), bucket['max_ulp'],
                            bucket['exactly_rounded_pct']))
        lines.append('')
        worst = max((bucket['max_ulp'] for bucket in function['buckets']), default=0)
        if worst == function['max_ulp']:
            lines.append('The maximum is %d ULP in the worst bucket and %d ULP overall: the error'
                         % (worst, function['max_ulp']))
            lines.append('does not grow with the argument.')
        else:
            lines.append('The maximum is %d ULP in the worst bucket and %d ULP overall: the bound'
                         % (worst, function['max_ulp']))
            lines.append('is declared per function, and the bucket rows say where it is spent.')
        lines.append('The rounding of the reference is done on the significand, never through')
        lines.append('`double`, which would round twice and disagree on exact ties.')
        lines.append('')
    with open(path, 'w', encoding='ascii', newline='\n') as handle:
        handle.write('\n'.join(lines))


# --------------------------------------------------------------------------- #
# main
# --------------------------------------------------------------------------- #


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', default=os.path.join(REPO, 'data', 'error-bounds.json'))
    parser.add_argument('--header', default=HEADER_PATH)
    parser.add_argument('--markdown', default=MARKDOWN_PATH)
    args = parser.parse_args(argv)

    with open(args.input, 'r', encoding='ascii') as handle:
        data = json.load(handle)

    if data.get('schema') != 1:
        raise SystemExit('%s: unexpected schema %r' % (args.input, data.get('schema')))
    for function in data['functions']:
        if not function['buckets']:
            raise SystemExit('%s: %s has no buckets' % (args.input, function['name']))

    emit_header(data, args.header)
    emit_markdown(data, args.markdown)
    for function in data['functions']:
        print('%-5s max %d ulp, %s points, %d buckets -> %s'
              % (function['name'], function['max_ulp'],
                 format(function['measured_points'], ','), len(function['buckets']),
                 os.path.relpath(args.header, REPO)))
    print('wrote %s' % os.path.relpath(args.markdown, REPO))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
