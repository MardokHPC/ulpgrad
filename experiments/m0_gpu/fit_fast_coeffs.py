#!/usr/bin/env python3
"""Degree-3/4 `Q(r)` coefficients for the Fast variants, same machinery as m0_exp.

`experiments/m0_exp/fit_coeffs.py --degree 3` fits correctly and then throws the
fit away: main() treats any mpmath residual above 1e-6 as "remez failed" and
falls back to a weighted least-squares path that, at low degree, comes back with
a 0.18 relative residual (the Chebyshev-in-t to monomial-in-r step in
fit_lstsq() is not a composition). Remez itself converges to 1.499e-5 at degree
3 and 4.330e-7 at degree 4, which says the fit is fine and the fallback is the
problem. Degree 6 does not hit this because its residual is 2.3e-10.

This script is that pipeline without the guard: remez(), float32 rendering, Ziv
refinement against the whole exp pipeline on the same tuning grid, and the same
emit_header(). Every coefficient it writes is generated by the fit; nothing is
typed by hand.

    python experiments/m0_gpu/fit_fast_coeffs.py --degree 3 --out experiments/m0_gpu/coeffs_fast3.h
    python experiments/m0_gpu/fit_fast_coeffs.py --degree 4 --out experiments/m0_gpu/coeffs_fast4.h
"""

import argparse
import os
import sys

import mpmath
import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_HERE, '..', 'm0_exp')))

import fit_coeffs as fc          # noqa: E402  (path set above)
import gen_reference as gr       # noqa: E402


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--degree', type=int, required=True)
    parser.add_argument('--iterations', type=int, default=10)
    parser.add_argument('--tuning-points', type=int, default=25000)
    parser.add_argument('--tuning-seed', type=lambda s: int(s, 0), default=0xC0FFEE01)
    parser.add_argument('--out', required=True)
    args = parser.parse_args(argv)

    mpmath.mp.dps = fc.MP_DPS
    ln2 = mpmath.log(2)
    hi = ln2 / 2
    lo = -hi

    print('fitting Q(r) on [%.17g, %.17g], degree %d, mpmath dps %d'
          % (float(lo), float(hi), args.degree, mpmath.mp.dps))

    coeffs, iters, converged = fc.remez(args.degree, lo, hi, max_iter=args.iterations)
    verify = [lo + (hi - lo) * i / 200000 for i in range(200001)]
    residual = max(abs(e) for e in fc._eval_rel_error(coeffs, verify))
    print('remez: %d iterations, converged=%s, max relative residual %.6e'
          % (iters, converged, float(residual)))
    print('note: fit_coeffs.py main() would reject this residual (> 1e-6) and fall '
          'back to the broken lstsq path; that guard is the only difference here')

    c32 = fc.to_float32(coeffs)

    ln2_f = float(ln2)
    ln2_hi = gr.bits_to_float(gr.float_to_bits(np.float32(ln2_f)) & 0xFFFFF000)
    ln2_lo = float(np.float32(ln2_f - ln2_hi))
    inv_ln2 = float(np.float32(1.0 / ln2_f))
    ovf = gr.bits_to_float(gr.first_overflow_bits())
    unf = gr.bits_to_float(gr.last_underflow_bits())

    pipeline = fc.Pipeline(c32, inv_ln2, ln2_hi, ln2_lo, ovf, unf)

    n_uni = int(args.tuning_points * 0.8)
    xs_uni = gr.uniform_sample(n_uni, args.tuning_seed).view(np.float32)
    rng = np.random.default_rng(args.tuning_seed)
    ks = rng.integers(-140, 120, size=args.tuning_points - n_uni)
    us = rng.uniform(-1.0, 1.0, size=args.tuning_points - n_uni)
    xs_r = (ks.astype(np.float64) * ln2_f + us * 0.5 * ln2_f).astype(np.float32)
    xs = np.concatenate([xs_uni, xs_r]).astype(np.float32)
    ref = gr.reference_bits(xs.view(np.uint32), 'tuning')

    before = fc.score(pipeline, xs, ref)
    print('tuning grid: %d points, max %d ulp before Ziv (%d points at max)'
          % (xs.size, before[0], before[1]))

    c32, final_score, ziv_passes = fc.ziv_refine(pipeline, xs, ref)
    print('tuning grid: max %d ulp after Ziv (%d points at max)'
          % (final_score[0], final_score[1]))

    meta = {
        'degree': args.degree,
        'method': ('Remez exchange on Chebyshev nodes, %d iteration(s), %s.'
                   % (iters, 'converged' if converged else 'stopped without convergence')),
        'verify_grid': 200001,
        'residual': float(residual),
        'ziv_passes': ziv_passes,
        'tuning_points': xs.size,
        'tuning_seed': args.tuning_seed,
        'tuning_ulp': final_score[0],
        'inv_ln2': inv_ln2,
        'ln2_hi': ln2_hi,
        'ln2_lo': ln2_lo,
        'ovf': ovf,
        'unf': unf,
    }
    fc.emit_header(args.out, c32, meta)

    # emit_header() is m0_exp's, so it writes m0_exp's provenance line and points
    # at measure.cpp for the reported bound. Both are wrong for a header used by
    # the GPU spike: rewrite the two comment lines (and only those).
    with open(args.out, 'r', encoding='ascii') as fh:
        text = fh.read()
    text = text.replace(
        '// Generated by experiments/m0_exp/fit_coeffs.py -- do not edit by hand.',
        '// Generated by experiments/m0_gpu/fit_fast_coeffs.py -- do not edit by hand.\n'
        '// The fit itself is the m0_exp machinery: Remez + float32 rendering + Ziv,\n'
        '// imported, run without the residual guard that rejects a low-degree fit.')
    text = text.replace(
        '// reported bound comes from measure.cpp on the full sample).',
        '// reported bound comes from exp_bench.cu on the full sample).')
    with open(args.out, 'w', encoding='ascii', newline='\n') as fh:
        fh.write(text)

    print('wrote %s' % args.out)
    for i, c in enumerate(c32):
        print('  c%d = %.9gf   %s' % (i, float(c), float(np.float32(c)).hex()))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
