// --------------------------------------------------------------------------- //
// merge mode: stitch the per-build part files into one report.json
// --------------------------------------------------------------------------- //

static int merge_reports(int argc, char** argv) {
    // argv[2] = output, argv[3..] = part files
    std::string body;
    for (int i = 3; i < argc; ++i) {
        FILE* f = std::fopen(argv[i], "rb");
        if (f == nullptr) {
            std::printf("cannot open %s\n", argv[i]);
            return 1;
        }
        std::string text;
        char buf[4096];
        size_t got = 0;
        while ((got = std::fread(buf, 1, sizeof buf, f)) > 0) {
            text.append(buf, got);
        }
        std::fclose(f);

        const size_t open = text.find('{');
        const size_t close = text.rfind('}');
        if (open == std::string::npos || close == std::string::npos || close <= open) {
            std::printf("%s does not contain a JSON object\n", argv[i]);
            return 1;
        }
        // Strip the outer braces and the trailing newline; the parts are
        // written one-property-per-line, so a plain join is valid JSON.
        // Keep the whole object, braces included: the parts go into an array of
        // objects, so stripping them here was a bug that produced invalid JSON.
        std::string inner = text.substr(open, close - open + 1);
        while (!inner.empty() && (inner.back() == '\n' || inner.back() == ' ')) {
            inner.pop_back();
        }
        if (!body.empty()) {
            body += ",\n";
        }
        body += inner;
    }

    FILE* out = std::fopen(argv[2], "wb");
    if (out == nullptr) {
        std::printf("cannot write %s\n", argv[2]);
        return 1;
    }
    std::fprintf(out, "{\n  \"runs\": [\n%s\n  ]\n}\n", body.c_str());
    std::fclose(out);
    std::printf("merged %d part(s) into %s\n", argc - 3, argv[2]);
    return 0;
}

// --------------------------------------------------------------------------- //
// main
// --------------------------------------------------------------------------- //

int main(int argc, char** argv) {
    if (argc >= 4 && std::strcmp(argv[1], "--merge") == 0) {
        return merge_reports(argc, argv);
    }

    const char* ref_path = (argc > 1) ? argv[1] : "..\\m0_exp\\ref.bin";
    const char* config_label = (argc > 2) ? argv[2] : "ftz=true fmad=true";
    const char* report_path = (argc > 3) ? argv[3] : "report.json";

    std::printf("ulp mapping self-check\n");
    verify_ulp_mapping();
    if (failures != 0) {
        std::printf("%d assertion(s) failed, refusing to report numbers\n", failures);
        return 1;
    }
    std::printf("  ok  monotone mapping and ulp_distance\n");

    // ---- device ----------------------------------------------------------
    int device_count = 0;
    cuda_check(cudaGetDeviceCount(&device_count), "cudaGetDeviceCount");
    if (device_count == 0) {
        std::printf("no CUDA device\n");
        return 1;
    }
    cuda_check(cudaSetDevice(0), "cudaSetDevice");
    cudaDeviceProp prop{};
    cuda_check(cudaGetDeviceProperties(&prop, 0), "cudaGetDeviceProperties");
    int runtime_version = 0;
    int driver_version = 0;
    cudaRuntimeGetVersion(&runtime_version);
    cudaDriverGetVersion(&driver_version);

    std::printf("\ndevice: %s (sm_%d%d, %d SMs, L2 %d KB, VRAM %d MB)\n", prop.name, prop.major,
                prop.minor, prop.multiProcessorCount, prop.l2CacheSize / 1024,
                static_cast<int>(prop.totalGlobalMem >> 20));
    g_sms = prop.multiProcessorCount;
    std::printf("cuda runtime %d.%d, driver %d.%d\n", runtime_version / 1000,
                (runtime_version % 1000) / 10, driver_version / 1000, (driver_version % 1000) / 10);
    std::printf("config: %s\n", config_label);

    // ---- reference sample ------------------------------------------------
    std::vector<Record> records;
    if (!read_records(ref_path, &records)) {
        std::printf("run experiments/m0_exp/run.bat first: it generates the reference sample\n");
        return 1;
    }
    const int ref_n = static_cast<int>(records.size());
    std::printf("reference sample: %d points from %s\n", ref_n, ref_path);

    // The host side must be the audited host spike, bit for bit, or the parity
    // number below compares against something else.
    std::vector<uint32_t> host_bits(records.size());
    uint64_t host_hash = kFnvOffset;
    std::vector<uint32_t> ref_x(records.size());
    for (size_t i = 0; i < records.size(); ++i) {
        ref_x[i] = records[i].x_bits;
        host_bits[i] = bits_of(host_exp(float_of(records[i].x_bits)));
        host_hash = (host_hash ^ static_cast<uint64_t>(host_bits[i])) * kFnvPrime;
    }
    const bool host_ok = (host_hash == kHostReferenceHash);
    std::printf("host reference hash        : 0x%016llX (measure.cpp printed 0x%016llX) %s\n",
                static_cast<unsigned long long>(host_hash),
                static_cast<unsigned long long>(kHostReferenceHash),
                host_ok ? "match" : "MISMATCH");
    if (!host_ok) {
        std::printf("the host reference is not the audited host spike: parity would be meaningless\n");
        return 1;
    }

    float* d_ref_in = nullptr;
    float* d_ref_out = nullptr;
    cuda_check(cudaMalloc(&d_ref_in, static_cast<size_t>(ref_n) * sizeof(float)), "malloc ref in");
    cuda_check(cudaMalloc(&d_ref_out, static_cast<size_t>(ref_n) * sizeof(float)), "malloc ref out");
    cuda_check(cudaMemcpy(d_ref_in, ref_x.data(), static_cast<size_t>(ref_n) * sizeof(float),
                          cudaMemcpyHostToDevice),
               "upload ref in");

    // ---- correctness: ULP per function on the reference sample -----------
    UlpStats ulp[kVariantCount];
    std::vector<uint32_t> out_bits(static_cast<size_t>(ref_n));
    for (int v = 0; v < kArithCount; ++v) {
        launch_variant(v, false, ref_n, 0, d_ref_in, d_ref_out);
        cuda_check(cudaDeviceSynchronize(), "ulp launch");
        cuda_check(cudaMemcpy(out_bits.data(), d_ref_out, static_cast<size_t>(ref_n) * sizeof(float),
                              cudaMemcpyDeviceToHost),
                   "download ref out");
        ulp[v] = analyse(kVariantName[v], records, out_bits);
    }

    // ---- parity host vs device, on the same inputs -----------------------
    // Re-run ulp_exp because out_bits now holds sfu___exp2f.
    launch_variant(kUlpExp, false, ref_n, 0, d_ref_in, d_ref_out);
    cuda_check(cudaDeviceSynchronize(), "parity launch");
    std::vector<uint32_t> device_bits(static_cast<size_t>(ref_n));
    cuda_check(cudaMemcpy(device_bits.data(), d_ref_out, static_cast<size_t>(ref_n) * sizeof(float),
                          cudaMemcpyDeviceToHost),
               "download parity out");

    Parity parity;
    parity.points = records.size();
    parity.min_diff_x = 0xFFFFFFFFu;
    for (size_t i = 0; i < records.size(); ++i) {
        if (device_bits[i] == host_bits[i]) {
            continue;
        }
        if (parity.diffs == 0) {
            parity.first_diff = static_cast<uint32_t>(i);
            parity.first_diff_x = records[i].x_bits;
            parity.first_diff_device = device_bits[i];
            parity.first_diff_host = host_bits[i];
        }
        ++parity.diffs;
        const uint32_t xb = records[i].x_bits;
        if (xb < parity.min_diff_x) parity.min_diff_x = xb;
        if (xb > parity.max_diff_x) parity.max_diff_x = xb;
        if (device_bits[i] == 0u) ++parity.diff_device_zero;
        if ((records[i].ref_bits & 0x7F800000u) == 0u) ++parity.diff_ref_subnormal;
    }
    if (parity.diffs == 0) {
        parity.min_diff_x = 0;
    }

    // ---- subnormal-output sweep ------------------------------------------
    // The 255 sample points whose result is subnormal are the reason this file
    // changed, but 255 points is thin evidence for a branch with several edge
    // cases in it (s = 1 .. 24, an m that rounds up into 0x00800000, and the
    // exact +0 below the underflow threshold). The whole range is walked
    // densely here and every result is compared bit for bit with the audited
    // host path, which uses the float multiply that -ftz=true would flush.
    const int kSubN = 1 << 16;
    const double sub_lo = -104.0;
    const double sub_hi = -86.0;
    std::vector<uint32_t> sub_x(static_cast<size_t>(kSubN));
    for (int i = 0; i < kSubN; ++i) {
        const double t = sub_lo + (sub_hi - sub_lo) * static_cast<double>(i) /
                                     static_cast<double>(kSubN - 1);
        sub_x[static_cast<size_t>(i)] = bits_of(static_cast<float>(t));
    }
    cuda_check(cudaMemcpy(d_ref_in, sub_x.data(), static_cast<size_t>(kSubN) * sizeof(float),
                          cudaMemcpyHostToDevice),
               "upload subnormal sweep");
    launch_variant(kUlpExp, false, kSubN, 0, d_ref_in, d_ref_out);
    cuda_check(cudaDeviceSynchronize(), "subnormal sweep launch");
    std::vector<uint32_t> sub_dev(static_cast<size_t>(kSubN));
    cuda_check(cudaMemcpy(sub_dev.data(), d_ref_out, static_cast<size_t>(kSubN) * sizeof(float),
                          cudaMemcpyDeviceToHost),
               "download subnormal sweep");
    uint64_t sub_diffs = 0;
    uint64_t sub_subnormal = 0;
    uint64_t sub_zero = 0;
    uint64_t sub_smallest_normal = 0;
    uint64_t sub_largest_subnormal = 0;
    for (int i = 0; i < kSubN; ++i) {
        const uint32_t h = bits_of(host_exp(float_of(sub_x[static_cast<size_t>(i)])));
        const uint32_t g = sub_dev[static_cast<size_t>(i)];
        if (h != g) ++sub_diffs;
        if (g == 0u) ++sub_zero;
        if ((g & 0x7F800000u) == 0u && (g & 0x007FFFFFu) != 0u) ++sub_subnormal;
        if (g == 0x00800000u) ++sub_smallest_normal;
        if (g == 0x007FFFFFu) ++sub_largest_subnormal;
    }

    // Are the two encoding edges reachable at all? The normal/subnormal
    // boundary is 2^-126 = exp(-126 ln2), and a half-ULP window around it is
    // 2^-24 relative; one ULP of the argument near -87.34 moves the result by
    // 2^-17 absolute, i.e. far more than that. Quantified rather than assumed:
    const double boundary_x = -126.0 * std::log(2.0);
    const float boundary_f = static_cast<float>(boundary_x);
    const float bracket_lo = std::nextafter(boundary_f, -1.0e9f);
    const float bracket_hi = std::nextafter(boundary_f, 1.0e9f);
    const double ulp_lo = (std::exp(static_cast<double>(bracket_lo)) * std::ldexp(1.0, 126) - 1.0) /
                          std::ldexp(1.0, -24);
    const double ulp_hi = (std::exp(static_cast<double>(bracket_hi)) * std::ldexp(1.0, 126) - 1.0) /
                          std::ldexp(1.0, -24);

    // ---- throughput ------------------------------------------------------
    std::vector<float> input;
    fill_input(&input);
    float* d_in = nullptr;
    float* d_out = nullptr;
    cuda_check(cudaMalloc(&d_in, static_cast<size_t>(kBenchN) * sizeof(float)), "malloc bench in");
    cuda_check(cudaMalloc(&d_out, static_cast<size_t>(kBenchN) * sizeof(float)), "malloc bench out");
    cuda_check(cudaMemcpy(d_in, input.data(), static_cast<size_t>(kBenchN) * sizeof(float),
                          cudaMemcpyHostToDevice),
               "upload bench in");

    // Clock ramp. Measured, not assumed: without this burst the first timed
    // variant in the process came out 14 % slower than the same variant
    // measured later in the same process (see the reverse-order control), which
    // is a GPU boost-state artifact, not a property of the function. 800 copy
    // launches are ~0.3 s of continuous work at DRAM speed.
    for (int i = 0; i < 800; ++i) {
        launch_variant(kCopy, false, kBenchN, 0, d_in, d_out);
    }
    for (int i = 0; i < 100; ++i) {
        launch_variant(kUlpExp, false, kBenchN, 0, d_in, d_out);
    }
    cuda_check(cudaDeviceSynchronize(), "clock ramp");

    // Three sweeps, because one number cannot answer the question:
    //   dram       16 M floats (128 MB of traffic): what a real pipeline sees,
    //              and necessarily memory-bound if the function is cheap;
    //   dram_rev   the same sweep in reverse order: the control for clock drift
    //              between runs, which is what a single sweep cannot show;
    //   l2         256 K floats (2 MB, fits in the 4 MB L2): the memory wall is
    //              gone, so this is the arithmetic cost of each function.
    // Every timed launch is repeated `inner` times between the two events so
    // the event overhead stays under 1 % of the measured interval.
    static Series dram;
    static Series dram_rev;
    static Series l2;
    if (!run_series(kBenchN, 0, 1, kWarmup, kIters, false, 2, d_in, d_out, &dram)) return 1;
    if (!run_series(kBenchN, 0, 1, 2, kIters, true, 2, d_in, d_out, &dram_rev)) return 1;
    if (!run_series(kL2N, kL2Reps, 1, 5, kL2Iters, false, 1, d_in, d_out, &l2)) return 1;

    // ---- stdout ----------------------------------------------------------
    char title[200];
    std::snprintf(title, sizeof title,
                  "throughput, DRAM (N = %d floats = %.0f MB in + %.0f MB out, %d threads/block)",
                  kBenchN, kBenchN * 4.0 / 1.0e6, kBenchN * 4.0 / 1.0e6, kBlock);
    print_series(title, dram);
    print_series("throughput, DRAM, reverse order (control for clock drift)", dram_rev);
    std::snprintf(title, sizeof title,
                  "throughput, latency-bound, working set in L2 (N = %d floats = %.0f MB, %d"
                  " repeats, full grid)",
                  kL2N, kL2N * 8.0 / 1.0e6, kL2Reps);
    print_series(title, l2);
    std::printf("note: a %% copy above 100 is run-to-run noise, not a faster copy\n");

    std::printf("\nstability: median ms, forward vs reverse order (same process)\n");
    std::printf("%-16s %-5s %10s %10s %8s\n", "variant", "vec", "forward", "reverse", "delta");
    double worst_delta = 0.0;
    for (int i = 0; i < dram.nrows; ++i) {
        const BenchRow& a = dram.rows[i];
        const BenchRow& b = dram_rev.rows[i];
        const double delta = 100.0 * (b.t.median_ms - a.t.median_ms) / a.t.median_ms;
        worst_delta = std::max(worst_delta, std::fabs(delta));
        std::printf("%-16s %-5s %10.4f %10.4f %7.1f%%\n", kVariantName[a.variant],
                    a.vec ? "f4" : "1", a.t.median_ms, b.t.median_ms, delta);
    }
    std::printf("worst forward/reverse disagreement: %.1f%%\n", worst_delta);

    std::printf("\noutput hashes (FNV-1a over %d result bit patterns, DRAM input)\n", kBenchN);
    for (int i = 0; i < dram.nrows; ++i) {
        std::printf("  %-16s %-5s 0x%016llX\n", kVariantName[dram.rows[i].variant],
                    dram.rows[i].vec ? "f4" : "1",
                    static_cast<unsigned long long>(dram.rows[i].hash));
    }

    std::printf("\n=== ULP on the reference sample (%d points) ===\n", ref_n);
    std::printf("%-16s %10s %8s %6s %6s %6s %8s %8s\n", "function", "points", "max ulp", "p50",
                "p99", "p999", "> 1 ulp", "== 0");
    for (int v = 0; v < kArithCount; ++v) {
        const UlpStats& s = ulp[v];
        std::printf("%-16s %10llu %8u %6u %6u %6u %8llu %7.2f%%\n", s.name,
                    static_cast<unsigned long long>(s.points), s.max_ulp, s.p50, s.p99, s.p999,
                    static_cast<unsigned long long>(s.gt1),
                    100.0 * static_cast<double>(s.eq0) / static_cast<double>(s.points));
    }

    std::printf("\nworst point per function\n");
    for (int v = 0; v < kArithCount; ++v) {
        const UlpStats& s = ulp[v];
        if (s.max_ulp == 0u) {
            std::printf("  %-16s max 0 ulp (exactly rounded everywhere)\n", s.name);
            continue;
        }
        const Record& r = records[s.argmax];
        const float x = float_of(r.x_bits);
        const float kf = std::rint(x * inv_ln2);
        const float rr = std::fma(-static_cast<float>(kf), ln2_lo,
                                  std::fma(-kf, ln2_hi, x));
        std::printf("  %-16s x = %.9g (0x%08X), k = %d, r = %.9g, ulp %u\n", s.name,
                    static_cast<double>(x), r.x_bits, static_cast<int>(kf),
                    static_cast<double>(rr), s.max_ulp);
    }

    std::printf("\nmax ulp per |x| bucket (the argument-degradation evidence)\n");
    std::printf("%-16s", "function");
    for (int b = 0; b < kBuckets; ++b) {
        std::printf(" %9s", kBucketLabel[b]);
    }
    std::printf("\n");
    for (int v = 0; v < kArithCount; ++v) {
        std::printf("%-16s", ulp[v].name);
        for (int b = 0; b < kBuckets; ++b) {
            std::printf(" %9u", ulp[v].bucket_max[b]);
        }
        std::printf("\n");
    }

    std::printf("\n=== parity host vs device (ulp_exp on %d points) ===\n", ref_n);
    std::printf("differing bit patterns     : %llu of %llu\n",
                static_cast<unsigned long long>(parity.diffs),
                static_cast<unsigned long long>(parity.points));
    if (parity.diffs != 0) {
        std::printf("first difference           : index %u, x = %.9g (0x%08X)\n", parity.first_diff,
                    static_cast<double>(float_of(parity.first_diff_x)), parity.first_diff_x);
        std::printf("  device 0x%08X / host 0x%08X\n", parity.first_diff_device,
                    parity.first_diff_host);
        std::printf("differences whose device result is +0 : %llu\n",
                    static_cast<unsigned long long>(parity.diff_device_zero));
        std::printf("differences whose reference is subnormal : %llu\n",
                    static_cast<unsigned long long>(parity.diff_ref_subnormal));
        std::printf("x range of the differences : %.9g .. %.9g (0x%08X .. 0x%08X)\n",
                    static_cast<double>(float_of(parity.min_diff_x)),
                    static_cast<double>(float_of(parity.max_diff_x)), parity.min_diff_x,
                    parity.max_diff_x);
    }

    std::printf("\n=== subnormal-output sweep (ulp_exp, %d points in [%.0f, %.0f]) ===\n", kSubN,
                sub_lo, sub_hi);
    std::printf("bit differences vs the host path : %llu of %d\n",
                static_cast<unsigned long long>(sub_diffs), kSubN);
    std::printf("device outputs subnormal         : %llu\n",
                static_cast<unsigned long long>(sub_subnormal));
    std::printf("device outputs +0                : %llu\n",
                static_cast<unsigned long long>(sub_zero));
    std::printf("rounded up into 0x00800000       : %llu\n",
                static_cast<unsigned long long>(sub_smallest_normal));
    std::printf("largest subnormal 0x007FFFFF     : %llu\n",
                static_cast<unsigned long long>(sub_largest_subnormal));
    std::printf("boundary 2^-126: the two closest float32 arguments sit at %+.0f and %+.0f ulp of\n"
                "  2^-126 (1 ulp = 2^-24 relative), and the window that lands on 0x00800000 or\n"
                "  0x007FFFFF is +-0.5 ulp: no float32 argument reaches it\n",
                ulp_lo, ulp_hi);

    // ---- occupancy of the latency-bound probe ----------------------------
    // A long dependency chain is only latency-exposed when there are not enough
    // warps to hide it, so the number that explains (or fails to explain) the
    // 1.65x is resident warps per SM, not just instruction count.
    int occ_regs[kVariantCount];
    int occ_blocks[kVariantCount];
    for (int v = 0; v < kVariantCount; ++v) {
        occ_regs[v] = 0;
        occ_blocks[v] = 0;
        occupancy_row(v, &occ_regs[v], &occ_blocks[v]);
    }
    std::printf("\ntheoretical occupancy of the L2 probe (%d threads/block, %d threads/SM max)\n",
                kBlock, prop.maxThreadsPerMultiProcessor);
    std::printf("%-16s %6s %8s %7s %10s\n", "variant", "regs", "blocks", "warps", "occupancy");
    for (int v = 0; v < kVariantCount; ++v) {
        std::printf("%-16s %6d %8d %7d %9.1f%%\n", kVariantName[v], occ_regs[v], occ_blocks[v],
                    occ_blocks[v] * kBlock / 32,
                    100.0 * occ_blocks[v] * kBlock /
                        static_cast<double>(prop.maxThreadsPerMultiProcessor));
    }

    std::printf("\n=== verdict inputs ===\n");
    const BenchRow& d_ours = dram.rows[kUlpExp];
    const BenchRow& d_lib = dram.rows[kLibdeviceExpf];
    const BenchRow& d_fast = dram.rows[kFastExpf];
    std::printf("DRAM (memory-bound)  ulp_exp %.1f%% of copy, %.2fx libdevice expf, %.2fx __expf\n",
                100.0 * gb_per_s(d_ours.t, kBenchN) / copy_floor_gbs(dram, false),
                d_ours.t.median_ms / d_lib.t.median_ms, d_ours.t.median_ms / d_fast.t.median_ms);
    std::printf("L2 (latency-bound)   ulp_exp %.2fx copy, %.2fx libdevice expf, %.2fx __expf\n",
                l2.rows[kUlpExp].t.median_ms / l2.rows[kCopy].t.median_ms,
                l2.rows[kUlpExp].t.median_ms / l2.rows[kLibdeviceExpf].t.median_ms,
                l2.rows[kUlpExp].t.median_ms / l2.rows[kFastExpf].t.median_ms);
    std::printf("ULP: ulp_exp max %u, libdevice expf max %u (%llu points > 1), __expf max %u"
                " (%llu points > 1)\n",
                ulp[kUlpExp].max_ulp, ulp[kLibdeviceExpf].max_ulp,
                static_cast<unsigned long long>(ulp[kLibdeviceExpf].gt1), ulp[kFastExpf].max_ulp,
                static_cast<unsigned long long>(ulp[kFastExpf].gt1));

    std::printf("\nlatency-bound sweep (L2), function by function\n");
    std::printf("%-16s %9s %9s %9s %8s %8s\n", "variant", "ns/elem", "x copy", "x ulp_exp",
                "max ulp", ">1 ulp");
    const double copy_ms = l2.rows[kCopy].t.median_ms;
    for (int v = 0; v < kArithCount; ++v) {
        const BenchRow& r = l2.rows[v];
        std::printf("%-16s %9.4f %9.3f %9.3f %8u %8llu\n", kVariantName[v],
                    r.t.median_ms * 1.0e6 / static_cast<double>(total_elements(l2)),
                    r.t.median_ms / copy_ms, r.t.median_ms / l2.rows[kUlpExp].t.median_ms,
                    ulp[v].max_ulp, static_cast<unsigned long long>(ulp[v].gt1));
    }

    // ---- report part -----------------------------------------------------
    FILE* out = std::fopen(report_path, "wb");
    if (out == nullptr) {
        std::printf("cannot write %s\n", report_path);
        return 1;
    }
    std::fprintf(out, "  {\n");
    std::fprintf(out, "    \"config\": \"%s\",\n", config_label);
    std::fprintf(out, "    \"device\": \"%s\",\n", prop.name);
    std::fprintf(out, "    \"compute_capability\": \"%d.%d\",\n", prop.major, prop.minor);
    std::fprintf(out, "    \"sms\": %d,\n", prop.multiProcessorCount);
    std::fprintf(out, "    \"cuda_runtime\": %d,\n", runtime_version);
    std::fprintf(out, "    \"cuda_driver\": %d,\n", driver_version);
    std::fprintf(out, "    \"bench_n\": %d,\n", kBenchN);
    std::fprintf(out, "    \"ref_points\": %d,\n", ref_n);
    std::fprintf(out, "    \"block\": %d,\n", kBlock);
    std::fprintf(out, "    \"warmup\": %d,\n", kWarmup);
    std::fprintf(out, "    \"iterations\": %d,\n", kIters);
    std::fprintf(out, "    \"l2_n\": %d,\n", kL2N);
    std::fprintf(out, "    \"l2_repeats\": %d,\n", kL2Reps);
    std::fprintf(out, "    \"l2_iterations\": %d,\n", kL2Iters);
    std::fprintf(out, "    \"host_reference_hash\": \"0x%016llX\",\n",
                 static_cast<unsigned long long>(host_hash));
    std::fprintf(out, "    \"throughput_dram\": [\n");
    for (int i = 0; i < dram.nrows; ++i) {
        const BenchRow& r = dram.rows[i];
        const double floor_gbs = copy_floor_gbs(dram, r.vec);
        std::fprintf(out,
                     "      {\"variant\": \"%s\", \"vector\": \"%s\", \"median_ms\": %.6f, "
                     "\"p10_ms\": %.6f, \"p90_ms\": %.6f, \"ns_per_elem\": %.4f, "
                     "\"melem_per_s\": %.1f, \"gb_per_s\": %.1f, \"pct_of_copy\": %.1f, "
                     "\"output_hash\": \"0x%016llX\"}%s\n",
                     kVariantName[r.variant], r.vec ? "float4" : "scalar", r.t.median_ms,
                     r.t.p10_ms, r.t.p90_ms, r.t.median_ms * 1.0e6 / static_cast<double>(kBenchN),
                     static_cast<double>(kBenchN) / (r.t.median_ms * 1.0e3), gb_per_s(r.t, kBenchN),
                     100.0 * gb_per_s(r.t, kBenchN) / floor_gbs,
                     static_cast<unsigned long long>(r.hash), (i + 1 < dram.nrows) ? "," : "");
    }
    std::fprintf(out, "    ],\n");
    std::fprintf(out, "    \"throughput_dram_reverse_order\": [\n");
    for (int i = 0; i < dram_rev.nrows; ++i) {
        const BenchRow& r = dram_rev.rows[i];
        const double floor_gbs = copy_floor_gbs(dram_rev, r.vec);
        std::fprintf(out,
                     "      {\"variant\": \"%s\", \"vector\": \"%s\", \"median_ms\": %.6f, "
                     "\"p10_ms\": %.6f, \"p90_ms\": %.6f, \"ns_per_elem\": %.4f, "
                     "\"melem_per_s\": %.1f, \"gb_per_s\": %.1f, \"pct_of_copy\": %.1f}%s\n",
                     kVariantName[r.variant], r.vec ? "float4" : "scalar", r.t.median_ms,
                     r.t.p10_ms, r.t.p90_ms, r.t.median_ms * 1.0e6 / static_cast<double>(kBenchN),
                     static_cast<double>(kBenchN) / (r.t.median_ms * 1.0e3), gb_per_s(r.t, kBenchN),
                     100.0 * gb_per_s(r.t, kBenchN) / floor_gbs,
                     (i + 1 < dram_rev.nrows) ? "," : "");
    }
    std::fprintf(out, "    ],\n");
    std::fprintf(out, "    \"throughput_l2\": [\n");
    const int l2_total = static_cast<int>(total_elements(l2));
    for (int i = 0; i < l2.nrows; ++i) {
        const BenchRow& r = l2.rows[i];
        const double floor_gbs = copy_floor_gbs(l2, r.vec);
        std::fprintf(out,
                     "      {\"variant\": \"%s\", \"vector\": \"%s\", \"median_ms\": %.6f, "
                     "\"p10_ms\": %.6f, \"p90_ms\": %.6f, \"ns_per_elem\": %.4f, "
                     "\"melem_per_s\": %.1f, \"gb_per_s\": %.1f, \"pct_of_copy\": %.1f}%s\n",
                     kVariantName[r.variant], r.vec ? "float4" : "scalar", r.t.median_ms,
                     r.t.p10_ms, r.t.p90_ms, r.t.median_ms * 1.0e6 / static_cast<double>(l2_total),
                     static_cast<double>(l2_total) / (r.t.median_ms * 1.0e3),
                     gb_per_s(r.t, l2_total), 100.0 * gb_per_s(r.t, l2_total) / floor_gbs,
                     (i + 1 < l2.nrows) ? "," : "");
    }
    std::fprintf(out, "    ],\n");
    std::fprintf(out, "    \"ulp\": [\n");
    for (int v = 0; v < kArithCount; ++v) {
        const UlpStats& s = ulp[v];
        std::fprintf(out,
                     "      {\"function\": \"%s\", \"points\": %llu, \"max_ulp\": %u, "
                     "\"p50_ulp\": %u, \"p99_ulp\": %u, \"p999_ulp\": %u, \"count_ulp_gt_1\": %llu, "
                     "\"count_ulp_eq_0\": %llu, \"argmax_index\": %u, \"argmax_x\": %.9f, "
                     "\"argmax_x_bits\": \"0x%08X\", \"output_hash\": \"0x%016llX\", "
                     "\"nan_inputs\": %llu, \"nan_mismatches\": %llu, \"ref_inf_cases\": %llu, "
                     "\"ref_inf_mismatches\": %llu, \"other_special_mismatches\": %llu, "
                     "\"bucket_max_ulp\": [%u, %u, %u, %u, %u, %u, %u, %u]}%s\n",
                     s.name, static_cast<unsigned long long>(s.points), s.max_ulp, s.p50, s.p99,
                     s.p999, static_cast<unsigned long long>(s.gt1),
                     static_cast<unsigned long long>(s.eq0), s.argmax,
                     static_cast<double>(float_of(records[s.argmax].x_bits)),
                     records[s.argmax].x_bits, static_cast<unsigned long long>(s.hash),
                     static_cast<unsigned long long>(s.nan_inputs),
                     static_cast<unsigned long long>(s.nan_mismatch),
                     static_cast<unsigned long long>(s.ref_inf),
                     static_cast<unsigned long long>(s.ref_inf_mismatch),
                     static_cast<unsigned long long>(s.special_mismatch), s.bucket_max[0],
                     s.bucket_max[1], s.bucket_max[2], s.bucket_max[3], s.bucket_max[4],
                     s.bucket_max[5], s.bucket_max[6], s.bucket_max[7],
                     (v + 1 < kArithCount) ? "," : "");
    }
    std::fprintf(out, "    ],\n");
    std::fprintf(out, "    \"occupancy\": [\n");
    for (int v = 0; v < kVariantCount; ++v) {
        std::fprintf(out,
                     "      {\"variant\": \"%s\", \"regs_per_thread\": %d, "
                     "\"blocks_per_sm\": %d, \"warps_per_sm\": %d, \"occupancy_pct\": %.1f}%s\n",
                     kVariantName[v], occ_regs[v], occ_blocks[v], occ_blocks[v] * kBlock / 32,
                     100.0 * occ_blocks[v] * kBlock /
                         static_cast<double>(prop.maxThreadsPerMultiProcessor),
                     (v + 1 < kVariantCount) ? "," : "");
    }
    std::fprintf(out, "    ],\n");
    std::fprintf(out,
                 "    \"subnormal_sweep\": {\"points\": %d, \"bit_differences_vs_host\": %llu, "
                 "\"device_outputs_subnormal\": %llu, \"device_outputs_zero\": %llu, "
                 "\"rounded_into_smallest_normal\": %llu, \"largest_subnormal\": %llu, "
                 "\"boundary_minus_ulp\": %.3f, \"boundary_plus_ulp\": %.3f},\n",
                 kSubN, static_cast<unsigned long long>(sub_diffs),
                 static_cast<unsigned long long>(sub_subnormal),
                 static_cast<unsigned long long>(sub_zero),
                 static_cast<unsigned long long>(sub_smallest_normal),
                 static_cast<unsigned long long>(sub_largest_subnormal), ulp_lo, ulp_hi);
    std::fprintf(out,
                 "    \"parity\": {\"points\": %llu, \"bit_differences\": %llu, "
                 "\"first_diff_index\": %u, \"first_diff_x\": %.9f, "
                 "\"first_diff_device_bits\": \"0x%08X\", \"first_diff_host_bits\": \"0x%08X\", "
                 "\"diffs_with_device_zero\": %llu, \"diffs_with_subnormal_reference\": %llu, "
                 "\"diffs_min_x\": %.9f, \"diffs_max_x\": %.9f}\n",
                 static_cast<unsigned long long>(parity.points),
                 static_cast<unsigned long long>(parity.diffs), parity.first_diff,
                 static_cast<double>(float_of(parity.first_diff_x)), parity.first_diff_device,
                 parity.first_diff_host, static_cast<unsigned long long>(parity.diff_device_zero),
                 static_cast<unsigned long long>(parity.diff_ref_subnormal),
                 static_cast<double>(float_of(parity.min_diff_x)),
                 static_cast<double>(float_of(parity.max_diff_x)));
    std::fprintf(out, "  }");
    std::fclose(out);

    cudaFree(d_in);
    cudaFree(d_out);
    cudaFree(d_ref_in);
    cudaFree(d_ref_out);

    const bool bound_ok = (ulp[kUlpExp].max_ulp <= 1u) && (ulp[kUlpExp].nan_mismatch == 0) &&
                          (ulp[kUlpExp].ref_inf_mismatch == 0) &&
                          (ulp[kUlpExp].special_mismatch == 0);
    std::printf("\nverdict: ulp_exp max ulp %u -> %s\n", ulp[kUlpExp].max_ulp,
                bound_ok ? "within the 1.0 ulp target" : "ABOVE the 1.0 ulp target");
    std::printf("wrote %s\n", report_path);
    return 0;
}
