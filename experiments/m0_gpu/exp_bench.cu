// M0 GPU spike -- throughput, ULP error and host/device parity of a float-only
// exp(x) kernel on a real device, against libdevice expf, __expf and __exp2f.
//
// This file is evidence, not library code. It exists to answer one question
// with numbers: on a GPU, does a degree-6 float32 exp with an explicit
// __fmaf_rn chain have a reason to exist next to expf and __expf?
//
// Layout of the function under test: Cody-Waite reduction in two parts ->
// degree-6 minimax polynomial from ../m0_exp/coeffs.h -> exact 2^k
// reconstruction through the exponent field, with every product-plus-add an
// explicit __fmaf_rn (never a*b+c).
//
// The 2^k scaling is done on the bits, not with a float multiply: under the
// default -ftz=true a float multiply flushes a subnormal result to zero, which
// is what made the first version of this file report 8,388,582 ULP.
//
// Two functions named "exp" live here on purpose:
//   host_exp()   the audited host spike (experiments/m0_exp/measure.cpp), used
//                as the parity reference and validated against the hash that
//                measure.cpp printed over the same sample;
//   device_exp() the kernel body, bit-for-bit the same formula.
// The parity number is only worth something if host_exp() is proven to be the
// host spike, which is what kHostReferenceHash checks at startup.

