struct BenchRow {
    int variant = 0;
    bool vec = false;
    Timing t;
    uint64_t hash = kFnvOffset;
};

struct Parity {
    uint64_t points = 0;
    uint64_t diffs = 0;
    uint32_t first_diff = 0;
    uint32_t first_diff_x = 0;
    uint32_t first_diff_device = 0;
    uint32_t first_diff_host = 0;
    uint32_t min_diff_x = 0;
    uint32_t max_diff_x = 0;
    uint64_t diff_device_zero = 0;
    uint64_t diff_ref_subnormal = 0;
};

double gb_per_s(const Timing& t, int n) {
    // 4 bytes in + 4 bytes out per element.
    return (8.0 * static_cast<double>(n)) / (t.median_ms * 1.0e6);
}

// One full sweep of the five variants in both vectorisations, in a chosen
// order. Running the same sweep a second time with the order reversed is the
// only cheap way to tell a real 3 % difference from a clock that drifted
// between processes.
struct Series {
    int n = 0;
    int reps = 0;
    int inner = 1;
    int iters = 0;
    int nrows = 0;
    BenchRow rows[2 * kVariantCount];
    double copy_gbs[2] = {0.0, 0.0};   // [scalar, float4]
};

bool run_series(int n, int reps, int inner, int warmup, int iters, bool reversed, int vecs,
                const float* d_in, float* d_out, Series* s) {
    s->n = n;
    s->reps = reps;
    s->inner = inner;
    s->iters = iters;
    s->nrows = 0;

    std::vector<float> host_out(static_cast<size_t>(n));
    std::vector<uint32_t> bits(static_cast<size_t>(n));

    for (int pass = 0; pass < vecs; ++pass) {
        const int vec = reversed ? (vecs - 1 - pass) : pass;
        for (int step = 0; step < kVariantCount; ++step) {
            const int v = reversed ? (kVariantCount - 1 - step) : step;
            BenchRow row;
            row.variant = v;
            row.vec = (vec != 0);
            // Two rounds, keep the faster median: the GPU's clock state at the
            // start of a compute-heavy phase is not the steady state, and a
            // single round penalises whichever variant happens to be measured
            // first (measured: -6.3 % on the first variant of the sweep).
            Timing round1;
            Timing round2;
            if (!time_variant(v, row.vec, n, reps, inner, d_in, d_out, warmup, iters, &round1)) {
                return false;
            }
            if (!time_variant(v, row.vec, n, reps, inner, d_in, d_out, warmup, iters, &round2)) {
                return false;
            }
            row.t = (round2.median_ms < round1.median_ms) ? round2 : round1;
            if (reps == 0) {
                // Hash only for the plain kernels: the repeat probe writes the
                // same buffer `reps` times and says nothing new about the result.
                launch_variant(v, row.vec, n, 0, d_in, d_out);
                cuda_check(cudaDeviceSynchronize(), "hash launch");
                cuda_check(cudaMemcpy(host_out.data(), d_out,
                                      static_cast<size_t>(n) * sizeof(float),
                                      cudaMemcpyDeviceToHost),
                           "download bench out");
                std::memcpy(bits.data(), host_out.data(), static_cast<size_t>(n) * 4);
                row.hash = hash_bits(bits);
            }
            s->rows[s->nrows++] = row;
        }
    }

    // Locate the copy rows by name: they are the bandwidth floor of each group.
    const int total = n * (reps > 0 ? reps : 1);
    for (int i = 0; i < s->nrows; ++i) {
        if (s->rows[i].variant == kCopy) {
            s->copy_gbs[s->rows[i].vec ? 1 : 0] = gb_per_s(s->rows[i].t, total);
        }
    }
    // Report in a fixed order even when the measurement order was reversed.
    std::sort(s->rows, s->rows + s->nrows, [](const BenchRow& a, const BenchRow& b) {
        if (a.vec != b.vec) return !a.vec;
        return a.variant < b.variant;
    });
    return true;
}

double copy_floor_gbs(const Series& s, bool vec) { return s.copy_gbs[vec ? 1 : 0]; }

// Elements actually processed per timed interval: the repeat probe walks its
// buffer `reps` times, so its per-element numbers are comparable with the
// plain kernels instead of being divided by `reps` too much.
int64_t total_elements(const Series& s) {
    return static_cast<int64_t>(s.n) * static_cast<int64_t>(s.reps > 0 ? s.reps : 1);
}

void print_series(const char* title, const Series& s) {
    const int64_t total = total_elements(s);
    std::printf("\n=== %s ===\n", title);
    std::printf("%-16s %-5s %10s %10s %10s %10s %9s %8s %8s\n", "variant", "vec", "median ms",
                "p10 ms", "p90 ms", "ns/elem", "Melem/s", "GB/s", "% copy");
    for (int i = 0; i < s.nrows; ++i) {
        const BenchRow& r = s.rows[i];
        const double ns = r.t.median_ms * 1.0e6 / static_cast<double>(total);
        const double melem = static_cast<double>(total) / (r.t.median_ms * 1.0e3);
        std::printf("%-16s %-5s %10.4f %10.4f %10.4f %10.4f %9.1f %8.1f %7.1f%%\n",
                    kVariantName[r.variant], r.vec ? "f4" : "1", r.t.median_ms, r.t.p10_ms,
                    r.t.p90_ms, ns, melem, gb_per_s(r.t, static_cast<int>(total)),
                    100.0 * gb_per_s(r.t, static_cast<int>(total)) / copy_floor_gbs(s, r.vec));
    }
    if (s.copy_gbs[1] > 0.0) {
        std::printf("floor: %.1f GB/s scalar, %.1f GB/s float4 (8 B/element)\n", s.copy_gbs[0],
                    s.copy_gbs[1]);
    } else {
        std::printf("floor: %.1f GB/s scalar (8 B/element)\n", s.copy_gbs[0]);
    }
}

