bool read_records(const char* path, std::vector<Record>* records) {
    FILE* f = std::fopen(path, "rb");
    if (f == nullptr) {
        std::printf("cannot open %s\n", path);
        return false;
    }
    std::fseek(f, 0, SEEK_END);
    const long bytes = std::ftell(f);
    std::fseek(f, 0, SEEK_SET);
    if (bytes <= 0 || (bytes % 8) != 0) {
        std::printf("%s is not a multiple of 8 bytes\n", path);
        std::fclose(f);
        return false;
    }
    records->resize(static_cast<size_t>(bytes) / sizeof(Record));
    const size_t got = std::fread(records->data(), sizeof(Record), records->size(), f);
    std::fclose(f);
    if (got != records->size()) {
        std::printf("short read on %s\n", path);
        return false;
    }
    return true;
}

void cuda_check(cudaError_t e, const char* what) {
    if (e != cudaSuccess) {
        std::printf("CUDA error at %s: %s\n", what, cudaGetErrorString(e));
        std::exit(1);
    }
}

// Deterministic uniform input in [-30, 30): the range that matters for softmax
// and the same range as the host sample's uniform category, so the throughput
// numbers describe the fast path of every variant.
void fill_input(std::vector<float>* v) {
    v->resize(kBenchN);
    uint64_t s = 0x5EED0002ull;
    const double scale = 60.0 / 9007199254740992.0;   // 2^53
    for (int i = 0; i < kBenchN; ++i) {
        s = s * 6364136223846793005ull + 1442695040888963407ull;
        const double u = static_cast<double>(s >> 11) * scale;   // [0, 60)
        (*v)[static_cast<size_t>(i)] = static_cast<float>(u - 30.0);
    }
}

