constexpr float kInf = std::numeric_limits<float>::infinity();

uint32_t bits_of(float x) {
    uint32_t b = 0;
    std::memcpy(&b, &x, sizeof b);
    return b;
}

float float_of(uint32_t b) {
    float x = 0.0f;
    std::memcpy(&x, &b, sizeof x);
    return x;
}

bool is_nan_bits(uint32_t b) {
    return (b & 0x7F800000u) == 0x7F800000u && (b & 0x007FFFFFu) != 0u;
}

bool is_inf_bits(uint32_t b) {
    return (b & 0x7FFFFFFFu) == 0x7F800000u;
}

float power_of_two(int e) {
    return float_of(static_cast<uint32_t>(e + 127) << 23);
}

// --------------------------------------------------------------------------- //
// the function under test: host side (parity reference)
// --------------------------------------------------------------------------- //

float host_exp(float x) {
    if (std::isnan(x)) {
        return x;                        // payload and sign preserved, bit for bit
    }
    if (x >= overflow_threshold) {
        return kInf;
    }
    if (x <= underflow_threshold) {
        return 0.0f;                     // exp never returns -0
    }

    const float kf = std::rint(x * inv_ln2);
    const int k = static_cast<int>(kf);
    float r = std::fma(-kf, ln2_hi, x);
    r = std::fma(-kf, ln2_lo, r);

    float p = c6;
    p = std::fma(p, r, c5);
    p = std::fma(p, r, c4);
    p = std::fma(p, r, c3);
    p = std::fma(p, r, c2);
    p = std::fma(p, r, c1);
    p = std::fma(p, r, c0);
    const float y = std::fma(p, r, 1.0f);

    const uint32_t bits = bits_of(y);
    const int e = static_cast<int>((bits >> 23) & 0xFFu) + k;
    if (e >= 0xFF) {
        return kInf;
    }
    if (e > 0) {
        return float_of((bits & 0x807FFFFFu) | (static_cast<uint32_t>(e) << 23));
    }
    return (y * power_of_two(k + 64)) * power_of_two(-64);
}

// --------------------------------------------------------------------------- //
// the function under test: device side
// --------------------------------------------------------------------------- //

// Scaling by 2^k through the bits, never through a float multiply.
//
// The first version scaled with (y * 2^(k+64)) * 2^-64. Under -ftz=true (the
// CUDA default) that trailing multiply is a mul.f32 whose subnormal result is
// flushed to zero: 255 points, max 8,388,582 ULP, and libdevice expf does the
// same. Shifting the 24-bit significand onto the subnormal grid by hand costs a
// handful of integer instructions and is exact under either value of -ftz.
//
// y is exp(r) for |r| <= ln2/2 (or ex2.approx of the same), so its unbiased
// exponent is -1 or 0 and the rounding below is the only inexact step left.
__device__ __forceinline__ float scale_by_pow2(float y, int k) {
    const unsigned int iy = __float_as_uint(y);
    const int e = static_cast<int>(iy >> 23) + k - 127;   // exponent of the result
    if (e > 127) {
        return __int_as_float(0x7F800000);                // overflow
    }
    if (e >= -126) {
        return __uint_as_float(iy + (static_cast<unsigned int>(k) << 23));  // exact
    }
    // Subnormal result: drop s = -126 - e bits of the significand, round to
    // nearest even. An m that grows to 0x00800000 is the smallest normal, which
    // is exactly the next encoding, so no carry case is needed.
    const int s = -126 - e;                               // 1 .. 25
    if (s > 24) {
        return 0.0f;                                      // below half the smallest subnormal
    }
    unsigned int m = (iy & 0x007FFFFFu) | 0x00800000u;
    const unsigned int rem = m & ((1u << s) - 1u);
    const unsigned int half = 1u << (s - 1);
    m >>= s;
    if (rem > half || (rem == half && (m & 1u) != 0u)) {
        ++m;
    }
    return __uint_as_float(m);                            // exponent field 0 by construction
}

// Two-part Cody-Waite reduction, shared by every variant of ours.
__device__ __forceinline__ float reduce_r(float x, float* kf) {
    *kf = rintf(x * inv_ln2);
    float r = __fmaf_rn(-*kf, ln2_hi, x);
    r = __fmaf_rn(-*kf, ln2_lo, r);
    return r;
}

// Argument guards, identical for every variant of ours.
// Returns true when x needs the polynomial path.
__device__ __forceinline__ bool exp_guard(float x, float* out) {
    const unsigned int xb = __float_as_uint(x);
    if ((xb & 0x7FFFFFFFu) > 0x7F800000u) {
        *out = x;                        // NaN: payload preserved, bit for bit
        return false;
    }
    if (x >= overflow_threshold) {
        *out = __int_as_float(0x7F800000);
        return false;
    }
    if (x <= underflow_threshold) {
        *out = 0.0f;
        return false;
    }
    return true;
}

__device__ __forceinline__ float device_exp(float x) {
    float out;
    if (!exp_guard(x, &out)) {
        return out;
    }
    float kf;
    const float r = reduce_r(x, &kf);

    float p = c6;
    p = __fmaf_rn(p, r, c5);
    p = __fmaf_rn(p, r, c4);
    p = __fmaf_rn(p, r, c3);
    p = __fmaf_rn(p, r, c2);
    p = __fmaf_rn(p, r, c1);
    p = __fmaf_rn(p, r, c0);
    const float y = __fmaf_rn(p, r, 1.0f);
    return scale_by_pow2(y, static_cast<int>(kf));
}

// Same polynomial and the same coefficients, Estrin evaluation:
// Q(r) = (c0 + c1 r) + r^2 (c2 + c3 r) + r^4 ((c4 + c5 r) + r^2 c6).
// Chain length goes from 6 dependent fma to 4, at the cost of 2 extra muls.
__device__ __forceinline__ float device_exp_estrin(float x) {
    float out;
    if (!exp_guard(x, &out)) {
        return out;
    }
    float kf;
    const float r = reduce_r(x, &kf);

    const float r2 = r * r;
    const float r4 = r2 * r2;
    const float a = __fmaf_rn(c1, r, c0);
    const float b = __fmaf_rn(c3, r, c2);
    const float c = __fmaf_rn(c5, r, c4);
    const float t = __fmaf_rn(r2, b, a);
    const float u = __fmaf_rn(r2, c6, c);
    const float p = __fmaf_rn(r4, u, t);
    const float y = __fmaf_rn(p, r, 1.0f);
    return scale_by_pow2(y, static_cast<int>(kf));
}

// Q(r) with the degree-3 fit (generated by fit_fast_coeffs.py).
__device__ __forceinline__ float q_poly3(float r) {
    float p = fast3::c3;
    p = __fmaf_rn(p, r, fast3::c2);
    p = __fmaf_rn(p, r, fast3::c1);
    p = __fmaf_rn(p, r, fast3::c0);
    return p;
}

// Q(r) with the degree-4 fit.
__device__ __forceinline__ float q_poly4(float r) {
    float p = fast4::c4;
    p = __fmaf_rn(p, r, fast4::c3);
    p = __fmaf_rn(p, r, fast4::c2);
    p = __fmaf_rn(p, r, fast4::c1);
    p = __fmaf_rn(p, r, fast4::c0);
    return p;
}

template <int DEG>
__device__ __forceinline__ float device_exp_fast_poly(float x) {
    float out;
    if (!exp_guard(x, &out)) {
        return out;
    }
    float kf;
    const float r = reduce_r(x, &kf);
    const float q = (DEG == 3) ? q_poly3(r) : q_poly4(r);
    const float y = __fmaf_rn(q, r, 1.0f);
    return scale_by_pow2(y, static_cast<int>(kf));
}

