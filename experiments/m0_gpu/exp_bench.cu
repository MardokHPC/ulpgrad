// timing
// --------------------------------------------------------------------------- //

struct Timing {
    double median_ms = 0.0;
    double p10_ms = 0.0;
    double p90_ms = 0.0;
};

double percentile_f(std::vector<double> v, double p) {
    if (v.empty()) return 0.0;
    std::sort(v.begin(), v.end());
    const double n = static_cast<double>(v.size());
    double idx = std::ceil(p * n) - 1.0;
    if (idx < 0.0) idx = 0.0;
    if (idx > n - 1.0) idx = n - 1.0;
    return v[static_cast<size_t>(idx)];
}

bool time_variant(int variant, bool vec, int n, int reps, int inner, const float* d_in,
                  float* d_out, int warmup, int iters, Timing* out) {
    for (int i = 0; i < warmup; ++i) {
        launch_variant(variant, vec, n, reps, d_in, d_out);
    }
    if (cudaDeviceSynchronize() != cudaSuccess) {
        std::printf("launch error (%s): %s\n", kVariantName[variant], cudaGetErrorString(cudaGetLastError()));
        return false;
    }

    cudaEvent_t start = nullptr;
    cudaEvent_t stop = nullptr;
    cudaEventCreate(&start);
    cudaEventCreate(&stop);

    std::vector<double> ms;
    ms.reserve(kIters);
    for (int i = 0; i < iters; ++i) {
        cudaEventRecord(start);
        for (int r = 0; r < inner; ++r) {
            launch_variant(variant, vec, n, reps, d_in, d_out);
        }
        cudaEventRecord(stop);
        if (cudaEventSynchronize(stop) != cudaSuccess) {
            std::printf("sync error (%s)\n", kVariantName[variant]);
            return false;
        }
        float elapsed = 0.0f;
        cudaEventElapsedTime(&elapsed, start, stop);
        ms.push_back(static_cast<double>(elapsed) / static_cast<double>(inner));
    }
    cudaEventDestroy(start);
    cudaEventDestroy(stop);

    out->median_ms = percentile_f(ms, 0.50);
    out->p10_ms = percentile_f(ms, 0.10);
    out->p90_ms = percentile_f(ms, 0.90);
    return true;
}

