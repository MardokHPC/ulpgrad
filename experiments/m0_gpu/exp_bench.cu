// |x| buckets, used to show how each implementation degrades with the argument
// (the number the whole `Accurate` claim is about).
constexpr int kBuckets = 8;
const char* const kBucketLabel[kBuckets] = {
    "|x| < 1", "1 <= |x| < 2", "2 <= |x| < 4", "4 <= |x| < 8",
    "8 <= |x| < 16", "16 <= |x| < 32", "32 <= |x| < 64", "|x| >= 64",
};

int magnitude_bucket(float x) {
    const float a = std::fabs(x);
    if (!(a >= 1.0f)) return 0;   // also catches NaN
    if (a < 2.0f) return 1;
    if (a < 4.0f) return 2;
    if (a < 8.0f) return 3;
    if (a < 16.0f) return 4;
    if (a < 32.0f) return 5;
    if (a < 64.0f) return 6;
    return 7;
}

struct UlpStats {
    const char* name = "";
    uint64_t points = 0;
    uint32_t max_ulp = 0;
    uint32_t argmax = 0;
    uint32_t p50 = 0;
    uint32_t p99 = 0;
    uint32_t p999 = 0;
    uint64_t gt1 = 0;
    uint64_t gt0 = 0;
    uint64_t eq0 = 0;
    uint64_t nan_inputs = 0;
    uint64_t nan_mismatch = 0;
    uint64_t ref_inf = 0;
    uint64_t ref_inf_mismatch = 0;
    uint64_t special_mismatch = 0;
    uint64_t hash = kFnvOffset;
    uint32_t bucket_max[kBuckets] = {0, 0, 0, 0, 0, 0, 0, 0};
    uint64_t bucket_points[kBuckets] = {0, 0, 0, 0, 0, 0, 0, 0};
};

struct Record {
    uint32_t x_bits;
    uint32_t ref_bits;
};
static_assert(sizeof(Record) == 8, "ref.bin records are 8 bytes");

UlpStats analyse(const char* name, const std::vector<Record>& records,
                 const std::vector<uint32_t>& out_bits) {
    UlpStats s;
    s.name = name;
    std::vector<uint32_t> distances;
    distances.reserve(records.size());
    uint64_t h = kFnvOffset;

    for (size_t i = 0; i < records.size(); ++i) {
        const uint32_t xb = records[i].x_bits;
        const uint32_t rb = records[i].ref_bits;
        const uint32_t got = out_bits[i];
        h = (h ^ static_cast<uint64_t>(got)) * kFnvPrime;

        if (is_nan_bits(xb)) {
            ++s.nan_inputs;
            if (got != rb) {
                ++s.nan_mismatch;
            }
            continue;
        }
        if (is_nan_bits(rb)) {
            ++s.special_mismatch;
            continue;
        }
        if (is_inf_bits(rb)) {
            ++s.ref_inf;
            if (got != rb) {
                ++s.ref_inf_mismatch;
            }
        }
        if (is_nan_bits(got)) {
            ++s.special_mismatch;
            continue;
        }

        const uint32_t d = ulp_distance(got, rb);
        distances.push_back(d);
        if (d == 0u) {
            ++s.eq0;
        } else {
            ++s.gt0;
        }
        if (d > 1u) {
            ++s.gt1;
        }
        if (d > s.max_ulp) {
            s.max_ulp = d;
            s.argmax = static_cast<uint32_t>(i);
        }
        const int b = magnitude_bucket(float_of(xb));
        ++s.bucket_points[b];
        if (d > s.bucket_max[b]) {
            s.bucket_max[b] = d;
        }
    }

    s.points = distances.size();
    std::sort(distances.begin(), distances.end());
    s.p50 = percentile(distances, 0.50);
    s.p99 = percentile(distances, 0.99);
    s.p999 = percentile(distances, 0.999);
    s.hash = h;
    return s;
}

