enum Variant {
    kUlpExp = 0,
    kUlpExpEstrin = 1,
    kLibdeviceExpf = 2,
    kFastExpf = 3,
    kSfuExp2f = 4,
    kFastP3 = 5,
    kFastP4 = 6,
    kFastSfu = 7,
    kCopy = 8,
    kVariantCount = 9,
};

// Everything before kCopy is a function with ULP statistics; kCopy is the
// bandwidth floor and has no arithmetic to measure.
constexpr int kArithCount = kCopy;

const char* const kVariantName[kVariantCount] = {
    "ulp_exp",   "ulp_exp_estrin", "libdevice_expf", "fast___expf", "sfu_ex2_approx",
    "fast_p3",   "fast_p4",        "fast_sfu",       "copy",
};

// CUDA has no __exp2f intrinsic (checked in the 12.1/12.4/12.6 headers): the
// fastest exp2 is the SFU instruction itself, which is what __expf(x) is built
// from. Using it explicitly is the only way to name the floor below __expf.
__device__ __forceinline__ float ex2_approx(float x) {
    float r;
    asm("ex2.approx.f32 %0, %1;" : "=f"(r) : "f"(x));
    return r;
}

// Fast candidate 3: the SFU, but on the *reduced* residual instead of on the
// whole argument, so the 2^k scaling stays integer and exact. __expf is
// ex2.approx(x * log2 e) with no reduction, and its bound grows with |x|
// (63 ULP at 88.7) because that single multiply carries the argument's
// magnitude; here |r| <= ln2/2, so only the SFU's own error is left.
__device__ __forceinline__ float device_exp_fast_sfu(float x) {
    float out;
    if (!exp_guard(x, &out)) {
        return out;
    }
    float kf;
    const float r = reduce_r(x, &kf);
    const float y = ex2_approx(r * inv_ln2);
    return scale_by_pow2(y, static_cast<int>(kf));
}

template <int V>
__device__ __forceinline__ float apply_variant(float x) {
    if constexpr (V == kUlpExp) {
        return device_exp(x);
    } else if constexpr (V == kUlpExpEstrin) {
        return device_exp_estrin(x);
    } else if constexpr (V == kLibdeviceExpf) {
        return expf(x);
    } else if constexpr (V == kFastExpf) {
        return __expf(x);
    } else if constexpr (V == kSfuExp2f) {
        return ex2_approx(x * inv_ln2);  // 1.44269502f = log2(e), correctly rounded
    } else if constexpr (V == kFastP3) {
        return device_exp_fast_poly<3>(x);
    } else if constexpr (V == kFastP4) {
        return device_exp_fast_poly<4>(x);
    } else if constexpr (V == kFastSfu) {
        return device_exp_fast_sfu(x);
    } else {
        return x;                        // copy: the bandwidth floor
    }
}

template <int V>
__global__ void kernel_scalar(const float* __restrict__ in, float* __restrict__ out, int n) {
    const int i = static_cast<int>(blockIdx.x) * kBlock + static_cast<int>(threadIdx.x);
    if (i < n) {
        out[i] = apply_variant<V>(in[i]);
    }
}

template <int V>
__global__ void kernel_vec4(const float4* __restrict__ in, float4* __restrict__ out, int n4) {
    const int i = static_cast<int>(blockIdx.x) * kBlock + static_cast<int>(threadIdx.x);
    if (i < n4) {
        const float4 v = in[i];
        float4 r;
        r.x = apply_variant<V>(v.x);
        r.y = apply_variant<V>(v.y);
        r.z = apply_variant<V>(v.z);
        r.w = apply_variant<V>(v.w);
        out[i] = r;
    }
}

// Latency-bound probe: the buffer is small enough to stay in L2, the grid is
// large enough to fill the GPU, and every thread walks the buffer `reps` times.
// Same instruction mix per element as kernel_scalar, no launch-latency window.
// It is *not* arithmetic-bound in the throughput sense: the wall it hits is the
// dependency chain per element, with the working set already in L2.
template <int V>
__global__ void kernel_repeat(const float* __restrict__ in, float* __restrict__ out, int n,
                              int reps) {
    const int stride = static_cast<int>(gridDim.x) * kBlock;
    const int start = static_cast<int>(blockIdx.x) * kBlock + static_cast<int>(threadIdx.x);
    for (int r = 0; r < reps; ++r) {
        for (int i = start; i < n; i += stride) {
            out[i] = apply_variant<V>(in[i]);
        }
    }
}

int g_sms = 34;

#define ULPGRAD_LAUNCH(V, VEC)                                                                    \
    do {                                                                                          \
        if (reps > 0) {                                                                           \
            const int grid = g_sms * 8;                                                           \
            kernel_repeat<V><<<grid, kBlock>>>(in, out, n, reps);                                 \
        } else if (VEC) {                                                                         \
            const int n4 = n / 4;                                                                 \
            kernel_vec4<V><<<(n4 + kBlock - 1) / kBlock, kBlock>>>(                               \
                reinterpret_cast<const float4*>(in), reinterpret_cast<float4*>(out), n4);         \
        } else {                                                                                  \
            kernel_scalar<V><<<(n + kBlock - 1) / kBlock, kBlock>>>(in, out, n);                  \
        }                                                                                         \
    } while (0)

void launch_variant(int variant, bool vec, int n, int reps, const float* in, float* out) {
    switch (variant) {
        case kUlpExp:        ULPGRAD_LAUNCH(kUlpExp, vec); break;
        case kUlpExpEstrin:  ULPGRAD_LAUNCH(kUlpExpEstrin, vec); break;
        case kLibdeviceExpf: ULPGRAD_LAUNCH(kLibdeviceExpf, vec); break;
        case kFastExpf:      ULPGRAD_LAUNCH(kFastExpf, vec); break;
        case kSfuExp2f:      ULPGRAD_LAUNCH(kSfuExp2f, vec); break;
        case kFastP3:        ULPGRAD_LAUNCH(kFastP3, vec); break;
        case kFastP4:        ULPGRAD_LAUNCH(kFastP4, vec); break;
        case kFastSfu:       ULPGRAD_LAUNCH(kFastSfu, vec); break;
        default:             ULPGRAD_LAUNCH(kCopy, vec); break;
    }
}

// Theoretical occupancy of the latency-bound probe: the kernel that is 1.65x
// slower than copy is a dependency chain, and a chain with few resident warps
// is latency-exposed. Registers per thread and blocks per SM are the inputs to
// that argument, so they are measured rather than inferred from the build log.
template <int V>
void occupancy_of(int* regs, int* blocks) {
    cudaFuncAttributes attr{};
    cudaFuncGetAttributes(&attr, kernel_repeat<V>);
    int b = 0;
    cudaOccupancyMaxActiveBlocksPerMultiprocessor(&b, kernel_repeat<V>, kBlock, 0);
    *regs = attr.numRegs;
    *blocks = b;
}

bool occupancy_row(int variant, int* regs, int* blocks) {
    switch (variant) {
        case kUlpExp:        occupancy_of<kUlpExp>(regs, blocks); return true;
        case kUlpExpEstrin:  occupancy_of<kUlpExpEstrin>(regs, blocks); return true;
        case kLibdeviceExpf: occupancy_of<kLibdeviceExpf>(regs, blocks); return true;
        case kFastExpf:      occupancy_of<kFastExpf>(regs, blocks); return true;
        case kSfuExp2f:      occupancy_of<kSfuExp2f>(regs, blocks); return true;
        case kFastP3:        occupancy_of<kFastP3>(regs, blocks); return true;
        case kFastP4:        occupancy_of<kFastP4>(regs, blocks); return true;
        case kFastSfu:       occupancy_of<kFastSfu>(regs, blocks); return true;
        default:             occupancy_of<kCopy>(regs, blocks); return true;
    }
}

// --------------------------------------------------------------------------- //
// ULP distance on the monotone integer image of the float pattern
// --------------------------------------------------------------------------- //

int64_t monotone_key(uint32_t bits) {
    const int32_t s = static_cast<int32_t>(bits);
    if (s >= 0) {
        return static_cast<int64_t>(s);
    }
    return -static_cast<int64_t>(s & 0x7FFFFFFF);
}

uint32_t ulp_distance(uint32_t a, uint32_t b) {
    const int64_t d = monotone_key(a) - monotone_key(b);
    return static_cast<uint32_t>(d < 0 ? -d : d);
}

int failures = 0;

void check(bool ok, const char* what) {
    if (!ok) {
        std::printf("FAIL  %s\n", what);
        ++failures;
    }
}

void verify_ulp_mapping() {
    const float one = 1.0f;
    const float two = 2.0f;
    check(ulp_distance(bits_of(one), bits_of(std::nextafter(one, two))) == 1u,
          "+1.0 and its successor are 1 ulp apart");
    check(ulp_distance(bits_of(two), bits_of(1.0f)) == 8388608u,
          "1.0 and 2.0 are 2^23 ulp apart");
    check(ulp_distance(bits_of(0.0f), bits_of(-0.0f)) == 0u, "+0 and -0 are 0 ulp apart");
    check(ulp_distance(bits_of(1.0f), bits_of(-1.0f)) == 2130706432u,
          "+1.0 and -1.0 are 2*(2^30 - 2^23) ulp apart");
    check(ulp_distance(bits_of(float_of(1u)), 0u) == 1u, "smallest subnormal is 1 ulp from zero");
}

uint32_t percentile(const std::vector<uint32_t>& sorted, double p) {
    if (sorted.empty()) {
        return 0;
    }
    const double n = static_cast<double>(sorted.size());
    double idx = std::ceil(p * n) - 1.0;
    if (idx < 0.0) {
        idx = 0.0;
    }
    if (idx > n - 1.0) {
        idx = n - 1.0;
    }
    return sorted[static_cast<size_t>(idx)];
}

uint64_t hash_bits(const std::vector<uint32_t>& v) {
    uint64_t h = kFnvOffset;
    for (const uint32_t b : v) {
        h = (h ^ static_cast<uint64_t>(b)) * kFnvPrime;
    }
    return h;
}

